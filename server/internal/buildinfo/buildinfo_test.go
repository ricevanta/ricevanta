func TestCurrentReturnsDevelopmentDefault(t *testing.T) {
	got := buildinfo.Current()
	want := buildinfo.Identity{Version: "0.0.0-local", Commit: "unknown", Channel: "local", SourceEpoch: 0}
	if got != want {
		t.Fatalf("Current() = %+v, want %+v", got, want)
	}
}

func TestGeneratedFileIsIgnored(t *testing.T) {
	data, err := os.ReadFile("../../../.gitignore")
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range []string{
		"/server/internal/buildinfo/generated.go",
		"/server/internal/transport/console/dist/",
		"/server/internal/transport/console/manifest.json",
	} {
		if !containsLine(string(data), line) {
			t.Errorf(".gitignore lacks %q", line)
		}
	}
}

func containsLine(text, line string) bool {
	for _, l := range strings.Split(text, "\n") {
		if l == line {
			return true
		}
	}
	return false
}

// specGenerated is the generated.go shape fixed by docs/specs/server-runtime.md
// section 2: the four constants and an init function that assigns them.
const specGenerated = `// Code generated by scripts/release/version.py. DO NOT EDIT.
package buildinfo

const Version = "0.1.0-dev.0+g0123456789abcdef0123456789abcdef01234567"
const Commit = "0123456789abcdef0123456789abcdef01234567"
const Channel = "master"
const SourceEpoch int64 = 978307200

func init() { current = Identity{Version: Version, Commit: Commit, Channel: Channel, SourceEpoch: SourceEpoch} }
`

// versionPyGenerated is the exact output of scripts/release/version.py
// generate() for the same identity, as fixed by scripts/release/test_version.py.
const versionPyGenerated = `// Code generated by scripts/release/version.py. DO NOT EDIT.
package buildinfo

const Version = "0.1.0-dev.0+g0123456789abcdef0123456789abcdef01234567"
const Commit = "0123456789abcdef0123456789abcdef01234567"
const Channel = "master"
const SourceEpoch int64 = 978307200
`

// runWithGenerated builds the server command with generated.go added to the
// package through a build overlay, so the tracked tree never changes, and
// returns the output of version --json.
func runWithGenerated(t *testing.T, generated string) map[string]any {
	t.Helper()
	dir := t.TempDir()
	gen := filepath.Join(dir, "generated.go")
	if err := os.WriteFile(gen, []byte(generated), 0o600); err != nil {
		t.Fatal(err)
	}
	pkgDir, err := filepath.Abs(".")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(pkgDir, "generated.go")); err == nil {
		t.Skip("a generated.go is present in the package; this test checks the overlay case only")
	}
	overlay, err := json.Marshal(map[string]any{"Replace": map[string]string{filepath.Join(pkgDir, "generated.go"): gen}})
	if err != nil {
		t.Fatal(err)
	}
	overlayPath := filepath.Join(dir, "overlay.json")
	if err := os.WriteFile(overlayPath, overlay, 0o600); err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(dir, "ricevanta-server")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	build := exec.Command("go", "build", "-overlay", overlayPath, "-o", bin, "../../cmd/ricevanta-server")
	build.Env = append(os.Environ(), "GOPROXY=off", "GOFLAGS=-mod=readonly")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build with generated.go: %v\n%s", err, out)
	}
	out, err := exec.Command(bin, "version", "--json").Output()
	if err != nil {
		t.Fatalf("version --json: %v", err)
	}
	var got map[string]any
	if err := json.Unmarshal(out, &got); err != nil {
		t.Fatalf("decode %q: %v", out, err)
	}
	return got
}

func TestGeneratedFileOverridesDefaultThroughInit(t *testing.T) {
	got := runWithGenerated(t, specGenerated)
	want := map[string]any{
		"version":     "0.1.0-dev.0+g0123456789abcdef0123456789abcdef01234567",
		"commit":      "0123456789abcdef0123456789abcdef01234567",
		"channel":     "master",
		"sourceEpoch": float64(978307200),
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s = %v, want %v", k, got[k], v)
		}
	}
}

// TestVersionPyGeneratedFileCompiles confirms that the exact file written by
// scripts/release/version.py compiles into the package. It does not assert
// that the identity changes: that file has no init function, which the
// server runtime spec section 2 requires (reported as a design conflict).
func TestVersionPyGeneratedFileCompiles(t *testing.T) {
	got := runWithGenerated(t, versionPyGenerated)
	if got["version"] == nil {
		t.Fatalf("version --json lacks version: %v", got)
	}
}
