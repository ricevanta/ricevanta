func TestCurrentReturnsDevelopmentDefault(t *testing.T) {
	got := buildinfo.Current()
	want := buildinfo.Identity{Version: "0.0.0-local", Commit: "unknown", Channel: "local", SourceEpoch: 0}
	if got != want {
		t.Fatalf("Current() = %+v, want %+v", got, want)
	}
}

func TestGeneratedFileIsIgnored(t *testing.T) {
	data, err := os.ReadFile("../../../.gitignore")
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range []string{
		"/server/internal/buildinfo/generated.go",
		"/server/internal/transport/console/dist/",
		"/server/internal/transport/console/manifest.json",
	} {
		if !containsLine(string(data), line) {
			t.Errorf(".gitignore lacks %q", line)
		}
	}
}

func containsLine(text, line string) bool {
	for _, l := range strings.Split(text, "\n") {
		if l == line {
			return true
		}
	}
	return false
}

const (
	fixtureCommit  = "0123456789abcdef0123456789abcdef01234567"
	fixtureVersion = "0.1.0-dev.0+g" + fixtureCommit
)

// versionPyGenerated is generated.go exactly as release builds section 2
// fixes it and scripts/release/version.py writes it (test_version.py pins
// the same text): constants only, no build constraint, no other declaration.
const versionPyGenerated = "// Code generated by scripts/release/version.py. DO NOT EDIT.\n" +
	"package buildinfo\n\n" +
	"const Version = \"" + fixtureVersion + "\"\n" +
	"const Commit = \"" + fixtureCommit + "\"\n" +
	"const Channel = \"master\"\n" +
	"const SourceEpoch int64 = 978307200\n"

func copyDir(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, p)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

// moduleCopy copies the packages the server command needs into a temporary
// module, so generated.go never enters the tracked tree.
func moduleCopy(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	for _, f := range []string{"go.mod", "go.sum"} {
		data, err := os.ReadFile(filepath.Join("../..", f))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(root, f), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, dir := range []string{"cmd/ricevanta-server", "internal/buildinfo", "internal/platform", "internal/transport"} {
		copyDir(t, filepath.Join("../..", dir), filepath.Join(root, dir))
	}
	if _, err := os.Stat(filepath.Join(root, "internal/buildinfo/generated.go")); err == nil {
		t.Fatal("the tracked package holds a generated.go; remove it before running the tests")
	}
	return root
}

func goBuild(t *testing.T, root string, tags ...string) (string, []byte, error) {
	t.Helper()
	bin := filepath.Join(root, "ricevanta-server")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	args := []string{"build", "-o", bin}
	if len(tags) > 0 {
		args = append(args, "-tags", strings.Join(tags, ","))
	}
	cmd := exec.Command("go", append(args, "./cmd/ricevanta-server")...)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOPROXY=off", "GOFLAGS=-mod=readonly")
	out, err := cmd.CombinedOutput()
	return bin, out, err
}

func TestReleaseTagSelectsGeneratedIdentity(t *testing.T) {
	root := moduleCopy(t)
	if err := os.WriteFile(filepath.Join(root, "internal/buildinfo/generated.go"), []byte(versionPyGenerated), 0o644); err != nil {
		t.Fatal(err)
	}
	bin, out, err := goBuild(t, root, "ricevanta_release")
	if err != nil {
		t.Fatalf("release build: %v\n%s", err, out)
	}
	line, err := exec.Command(bin, "--version").Output()
	if err != nil {
		t.Fatal(err)
	}
	if want := "ricevanta-server " + fixtureVersion + " (commit " + fixtureCommit + ", channel master)\n"; string(line) != want {
		t.Fatalf("--version %q, want %q", line, want)
	}
	js, err := exec.Command(bin, "version", "--json").Output()
	if err != nil {
		t.Fatal(err)
	}
	want := `{"channel":"master","commit":"` + fixtureCommit + `","sourceEpoch":978307200,"version":"` + fixtureVersion + `"}` + "\n"
	if string(js) != want {
		t.Fatalf("version --json %q, want %q", js, want)
	}
	var decoded map[string]any
	if err := json.Unmarshal(js, &decoded); err != nil {
		t.Fatal(err)
	}
}

func TestReleaseTagWithoutGeneratedFileFailsToBuild(t *testing.T) {
	root := moduleCopy(t)
	if _, out, err := goBuild(t, root, "ricevanta_release"); err == nil {
		t.Fatalf("tag without generated.go built:\n%s", out)
	} else if !strings.Contains(string(out), "undefined") {
		t.Fatalf("unexpected failure:\n%s", out)
	}
}

func TestGeneratedFileWithoutReleaseTagFailsToBuild(t *testing.T) {
	root := moduleCopy(t)
	if err := os.WriteFile(filepath.Join(root, "internal/buildinfo/generated.go"), []byte(versionPyGenerated), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, out, err := goBuild(t, root); err == nil {
		t.Fatalf("generated.go without the tag built:\n%s", out)
	} else if !strings.Contains(string(out), "redeclared") {
		t.Fatalf("unexpected failure:\n%s", out)
	}
}
